#!/usr/bin/env node
// Generates the D1 seed migration for the skills catalog from skills/catalog.json,
// the single source of truth for the starter skills.
//
//   node scripts/gen-skills-seed.mjs            writes workers/edge/migrations/0001_seed_skills.sql
//
// After changing the catalog, add a NEW numbered migration instead of editing an applied one.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const catalog = JSON.parse(readFileSync(join(root, 'skills/catalog.json'), 'utf8'));
const out = process.argv[2] ?? 'workers/edge/migrations/0001_seed_skills.sql';
const quote = (value) => `'${String(value).replaceAll("'", "''")}'`;

const columns =
  'slug, name, name_es, summary, summary_es, needs, needs_es, icon, category, states, path, position, updated_at';
const statements = catalog.map((skill, position) => {
  const values = [
    quote(skill.slug),
    quote(skill.name),
    quote(skill.nameEs),
    quote(skill.summary),
    quote(skill.summaryEs),
    quote(skill.needs),
    quote(skill.needsEs),
    quote(skill.icon),
    quote(skill.category),
    quote(JSON.stringify(skill.states)),
    quote(skill.path),
    position,
    1763856000000,
  ].join(', ');
  return `INSERT OR REPLACE INTO skills (${columns}) VALUES (${values});`;
});

writeFileSync(
  join(root, out),
  `-- Generated by scripts/gen-skills-seed.mjs from skills/catalog.json. Do not edit by hand.\n${statements.join('\n--> statement-breakpoint\n')}\n`,
);
console.log(`Wrote ${statements.length} skills to ${out}`);
